// Generate curriculum/er-selection-transcripts.mjs from the T65 selection-clip decisions.
// Inputs are text only and tracked in Git: scripts/er-selection-clips.json (clip metadata,
// machine drafts, official candidates) and scripts/er-selection-decisions.mjs (chosen wording
// and evidence). Optional local ear-review decisions in the Git-ignored cache take precedence.
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { erSelectionDecisions } from './er-selection-decisions.mjs';

/** @typedef {'user' | 'official-asr' | 'asr-agreement' | 'asr-draft' | 'nonverbal'} Evidence */
/** @typedef {{ key: string, text: string }} Official */
/** @typedef {{ clip: string, sha256: string, characterId: string, family: 'selected' | 'selected2', skinCodes: number[], skinNames: string[], officials: Official[] }} Clip */
/** @typedef {{ status: 'confirmed' | 'nonverbal' | 'unclear', text: string, sha256: string }} EarDecision */

const { clips } = /** @type {{ clips: Clip[] }} */ (
  JSON.parse(await readFile('scripts/er-selection-clips.json', 'utf8'))
);
const earPath = '.cache/er-selection-all/review-decisions.json';
const ear = /** @type {Record<string, EarDecision>} */ (
  existsSync(earPath) ? JSON.parse(await readFile(earPath, 'utf8')) : {}
);

/** @param {string} text */
const comparable = (text) =>
  text
    .replace(/<[^>]*>/g, '')
    .normalize('NFKC')
    .replace(/[\s、。，,!?！？…・"~～ー.]/g, '');
/** @type {Record<Evidence, number>} */
const rank = { nonverbal: -1, 'asr-draft': 0, 'asr-agreement': 1, 'official-asr': 2, user: 3 };

/** @type {Map<string, { clips: number, withText: number, nonverbal: number, pending: number }>} */
const coverage = new Map();
/** @type {Map<string, { characterId: string, jp: string, evidence: Evidence, families: Set<string>, skinCodes: Set<number>, skinNames: Set<string>, officialKey: string | null, clipCount: number }>} */
const lines = new Map();
for (const clip of clips) {
  const cov = coverage.get(clip.characterId) ?? { clips: 0, withText: 0, nonverbal: 0, pending: 0 };
  cov.clips++;
  coverage.set(clip.characterId, cov);
  /** @type {Evidence | null} */
  let evidence = null;
  let jp = '';
  const earDecision = ear[`${clip.clip}.wav`];
  if (earDecision && earDecision.status !== 'unclear') {
    if (earDecision.sha256 !== clip.sha256)
      throw new Error(`Ear decision is for a different audio file: ${clip.clip}`);
    evidence = earDecision.status === 'nonverbal' ? 'nonverbal' : 'user';
    jp = earDecision.text.trim();
  } else if (erSelectionDecisions[clip.clip]) {
    [evidence, jp] = erSelectionDecisions[clip.clip];
  }
  if (!evidence) {
    cov.pending++;
    continue;
  }
  if (evidence === 'nonverbal') {
    cov.nonverbal++;
    continue;
  }
  if (!jp) throw new Error(`Decision without text: ${clip.clip}`);
  cov.withText++;
  const official = clip.officials.find((o) => comparable(o.text) === comparable(jp));
  if (evidence === 'official-asr' && !official)
    throw new Error(`official-asr text is not the fixed-version text: ${clip.clip}`);
  const key = `${clip.characterId}\u0000${comparable(jp)}`;
  const row = lines.get(key) ?? {
    characterId: clip.characterId,
    jp,
    evidence,
    families: new Set(),
    skinCodes: new Set(),
    skinNames: new Set(),
    officialKey: official?.key ?? null,
    clipCount: 0,
  };
  // The strongest evidence of any clip with this wording wins.
  if (rank[evidence] > rank[row.evidence]) row.evidence = evidence;
  row.families.add(clip.family);
  for (const code of clip.skinCodes) row.skinCodes.add(code);
  for (const name of clip.skinNames) row.skinNames.add(name);
  row.clipCount++;
  lines.set(key, row);
}

const rows = [...lines.values()].map((row) => ({
  characterId: row.characterId,
  jp: row.jp,
  evidence: row.evidence,
  families: [...row.families].sort(),
  skinCodes: [...row.skinCodes].sort((a, b) => a - b),
  skinNames: [...row.skinNames],
  officialKey: row.officialKey,
  clipCount: row.clipCount,
}));
const totals = [...coverage.values()].reduce(
  (t, c) => ({
    clips: t.clips + c.clips,
    withText: t.withText + c.withText,
    nonverbal: t.nonverbal + c.nonverbal,
    pending: t.pending + c.pending,
  }),
  { clips: 0, withText: 0, nonverbal: 0, pending: 0 },
);
const output = `/** Generated by scripts/build-er-selection-transcripts.mjs from the selection clips of game build 25617366.
 * evidence: user = confirmed by ear; official-asr = fixed-version text matched by speech recognition;
 * asr-agreement = two recognition models agree; asr-draft = edited machine draft (models disagree). Only "user" is ear-checked.
 * officialKey is set only when jp equals the fixed-version Japanese text. No audio, asset paths or hashes. */
/** @typedef {{ characterId: string, jp: string, evidence: 'user' | 'official-asr' | 'asr-agreement' | 'asr-draft', families: string[], skinCodes: number[], skinNames: string[], officialKey: string | null, clipCount: number }} SelectionTranscript */
/** @typedef {{ clips: number, withText: number, nonverbal: number, pending: number }} SelectionCoverage */
/** @type {Readonly<SelectionCoverage>} */
export const erSelectionTotals = Object.freeze(${JSON.stringify(totals)});
/** @type {Readonly<Record<string, SelectionCoverage>>} */
export const erSelectionCoverage = Object.freeze(${JSON.stringify(Object.fromEntries(coverage), null, 1)});
/** @type {readonly SelectionTranscript[]} */
export const erSelectionTranscripts = Object.freeze(${JSON.stringify(rows, null, 2)});
`;
await writeFile('curriculum/er-selection-transcripts.mjs', output);
console.log(JSON.stringify({ ...totals, uniqueLines: rows.length }));
