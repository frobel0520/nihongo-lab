import { audioPath } from './author.mjs';

// Original scenes with alternating voices. The same voice identifies a speaker
// throughout each scene; audio paths follow the existing content-addressing rule.
const voices = ['hau', 'nemo2'];

/**
 * @param {Omit<import('./lessons.mjs').Lesson, 'vocab' | 'grammar' | 'practice' | 'dialogue'> & {
 *   lines: [jp: string, reading: string, zh: string, ruby?: string][]
 * }} spec
 * @returns {import('./lessons.mjs').Lesson}
 */
function sceneLesson({ lines, ...lesson }) {
  return {
    ...lesson,
    vocab: [],
    grammar: [],
    practice: [],
    dialogue: lines.map(([jp, reading, zh, ruby], index) => {
      const voice = voices[index % voices.length];
      return {
        jp,
        reading,
        zh,
        voice,
        ...(ruby ? { ruby } : {}),
        audio: audioPath(`audio/stage-2/${lesson.id}`, 'dlg', jp, voice),
      };
    }),
  };
}

