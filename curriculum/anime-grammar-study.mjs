/** @param {string} lessonId @param {number} pointIndex @returns {GrammarStudy | undefined} */
export function grammarStudyFor(lessonId, pointIndex) {
  const row = rows[lessonId]?.[pointIndex];
  if (!row) return undefined;
  const [id, formation, ...questions] = row;
  return {
    id,
    formation,
    questions: questions.map(
      ([prompt, correct, distractors, explanation], i) => {
        // 每點兩題；答案位置跨點輪替，不以固定第一項讓使用者猜答案。
        const options = [correct, ...distractors];
        const answer =
          (Number(lessonId.slice(-2)) + pointIndex + i) % options.length;
        const rotated = [
          ...options.slice(options.length - answer),
          ...options.slice(0, options.length - answer),
        ];
        return {
          id: `q${i + 1}`,
          prompt,
          options: rotated,
          answer,
          explanation,
        };
      },
    ),
  };
}
